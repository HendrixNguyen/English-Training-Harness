import { mount } from '@vue/test-utils'
import { describe, expect, it } from 'vitest'
import ContentViewer from '~/components/learn/ContentViewer.vue'
import ItemPassage from '~/components/learn/ItemPassage.vue'
import AppButton from '~/components/ui/AppButton.vue'
import { classifyContent } from '~/utils/content'
const passage = 'Negotiated, then a contract.\nNegotiated again.'
const glossary = [{ term: 'negotiate', meaning_vi: 'đàm phán', definition: 'reach agreement' }, { term: 'contract', meaning_vi: 'hợp đồng', definition: 'an agreement' }]
const questions = [1, 2].map(n => ({ id: `q${n}`, prompt: `Question ${n}`, options: { A: 'Yes', B: 'No' } }))
const viewer = (data: unknown) => mount(ContentViewer, { props: { content: classifyContent(data), title: 'Reading' }, global: { components: { AppButton } } })
const button = (w: ReturnType<typeof viewer>, label: string) => w.findAll('button').find(b => b.text() === label)!
describe('reading passage viewer', () => {
  it('starts with passage, keeps sheet state between counted questions and emits only question answers', async () => {
    const w = viewer({ content: { passage, glossary, questions } })
    expect(w.text()).toContain('Đoạn văn')
    expect(w.text()).not.toContain('Question 1')
    await w.find('[aria-label="Giải nghĩa Negotiated"]').trigger('click')
    await button(w, 'Đọc xong →').trigger('click')
    expect(w.text()).toContain('Câu 1 / 2')
    expect(w.find('[aria-label="Giải nghĩa"]').exists()).toBe(false)
    expect(w.emitted('answer')).toBeUndefined()
    await button(w, 'Xem lại đoạn').trigger('click')
    expect(button(w, 'Ẩn đoạn văn').attributes('aria-expanded')).toBe('true')
    await w.find('[aria-label="Giải nghĩa contract"]').trigger('click')
    await w.find('[role="radio"]').trigger('click')
    await button(w, 'Trả lời').trigger('click')
    expect(w.text()).toContain('Câu 1 / 2')
    expect(w.text()).toContain('Đã trả lời 1 / 2')
    await button(w, 'Tiếp tục').trigger('click')
    expect(w.text()).toContain('Câu 2 / 2')
    expect(button(w, 'Ẩn đoạn văn').exists()).toBe(true)
    expect(w.find('[aria-label="Giải nghĩa"]').exists()).toBe(false)
    await button(w, 'Ẩn đoạn văn').trigger('click')
    expect(button(w, 'Xem lại đoạn').attributes('aria-expanded')).toBe('false')
    await w.find('[role="radio"]').trigger('click')
    await button(w, 'Trả lời').trigger('click')
    expect(w.emitted('finished')).toBeUndefined()
    await button(w, 'Tiếp tục').trigger('click')
    expect(w.emitted('answer')).toEqual([['q1', 'A'], ['q2', 'A']])
    expect(w.emitted('finished')).toHaveLength(1)
    w.unmount()
  })
  it('finishes zero-question passage and renders missing glossary as plain text', async () => {
    const w = viewer({ passage, questions: [] })
    expect(w.find('[role="region"]').text()).toBe(passage)
    expect(w.text()).not.toContain('Chạm vào')
    expect(w.find('[aria-label^="Giải nghĩa"]').exists()).toBe(false)
    await button(w, 'Đọc xong →').trigger('click')
    expect(w.emitted('finished')).toHaveLength(1)
    w.unmount()
  })
  it('switches and closes accessible glosses, returning keyboard focus on close and Escape', async () => {
    const w = mount(ItemPassage, { props: { passage, glossary }, attachTo: document.body })
    const terms = w.findAll<HTMLButtonElement>('button[aria-expanded]')
    expect(terms.every(t => t.element.tagName === 'BUTTON' && t.attributes('type') === 'button')).toBe(true)
    expect(terms.map(t => t.attributes('aria-label'))).toEqual(['Giải nghĩa Negotiated', 'Giải nghĩa contract'])
    terms[0]!.element.focus()
    await terms[0]!.trigger('click')
    expect(document.activeElement).toBe(terms[0]!.element)
    expect(terms[0]!.attributes('aria-expanded')).toBe('true')
    const card = () => w.find('[aria-label="Giải nghĩa"]')
    expect(card().attributes('aria-live')).toBe('polite')
    expect(card().attributes('id')).toBe(terms[0]!.attributes('aria-controls'))
    expect(card().text()).toContain('đàm phán')
    await terms[1]!.trigger('click')
    expect(card().text()).toContain('hợp đồng')
    await w.find('[aria-label="Đóng giải nghĩa"]').trigger('click')
    expect(document.activeElement).toBe(terms[1]!.element)
    await terms[0]!.trigger('click')
    await w.find('[aria-label="Đoạn văn"]').trigger('keydown', { key: 'Escape' })
    expect(card().exists()).toBe(false)
    expect(document.activeElement).toBe(terms[0]!.element)
    await terms[0]!.trigger('click')
    await terms[0]!.trigger('click')
    expect(card().exists()).toBe(false)
    expect(w.find('[aria-label="Đoạn văn"]').attributes('tabindex')).toBe('0')
    w.unmount()
  })
  it('preserves words and question fallback without exposing unavailable JSON', () => {
    for (const data of [{ questions }, { passage: ' ', questions }, { content: { questions } }]) {
      const w = viewer(data)
      expect(w.text()).toContain('Question 1')
      expect(w.text()).not.toContain('Xem lại đoạn')
      w.unmount()
    }
    const words = viewer({ words: [{ term: 'Hello', definition: 'Greeting' }], passage })
    expect(words.text()).toContain('Greeting')
    expect(words.text()).not.toContain('Đọc xong')
    words.unmount()
    const raw = viewer({ custom: '<script>' })
    expect(raw.find('pre').exists()).toBe(false)
    expect(raw.find('button').exists()).toBe(false)
    raw.unmount()
  })
})

describe('answer lessons', () => {
  it('guards unanswered submission and separates locked feedback from advance', async () => {
    const w = viewer({ questions: [{ ...questions[0], answer: 'B', explanation: 'The passage supports No.' }] })
    expect(w.text()).not.toContain('The passage supports No.')
    expect(button(w, 'Trả lời').attributes('disabled')).toBeDefined()
    await button(w, 'Trả lời').trigger('click')
    expect(w.emitted('finished')).toBeUndefined()
    await w.find('[role="radio"]').trigger('click')
    expect(w.text()).not.toContain('Đáp án đúng')
    await button(w, 'Trả lời').trigger('click')
    expect(w.text()).toContain('Trượt…')
    expect(w.text()).toContain('Đáp án đúng')
    expect(w.text()).toContain('The passage supports No.')
    expect(w.findAll('[role="radio"]').every(b => b.attributes('disabled') !== undefined)).toBe(true)
    expect(w.emitted('finished')).toBeUndefined()
    await button(w, 'Tiếp tục').trigger('click')
    expect(w.emitted('finished')).toHaveLength(1)
    w.unmount()
  })
})

describe('vocabulary and compatibility study', () => {
  it('shows every word and supplied example before the associated quiz, counting only submitted questions', async () => {
    const w = viewer({ words: [{ term: 'Inquire', definition: 'Ask for information', example: 'I inquire about the timetable.' }, { term: 'Reply', definition: 'Answer someone' }], questions })
    expect(w.text()).toContain('Từ 1 / 2'); expect(w.text()).toContain('I inquire about the timetable.'); expect(w.text()).not.toContain('Question 1')
    await button(w, 'Tiếp tục').trigger('click'); expect(w.text()).toContain('Từ 2 / 2'); expect(w.text()).toContain('Answer someone')
    await button(w, 'Làm câu hỏi').trigger('click'); expect(w.text()).toContain('Câu 1 / 2'); expect(w.text()).toContain('Đã trả lời 0 / 2')
    await w.find('[role="radio"]').trigger('keydown', { key: 'ArrowRight' }); expect(w.find('[aria-checked="true"]').text()).toContain('(B)')
    await button(w, 'Trả lời').trigger('click'); expect(w.text()).toContain('Đã ghi nhận lựa chọn'); expect(w.text()).not.toContain('Đáp án đúng')
    expect(w.emitted('answer')).toEqual([['q1', 'B']]); expect(w.emitted('finished')).toBeUndefined(); w.unmount()
  })
})
